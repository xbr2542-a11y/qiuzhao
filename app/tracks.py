def track_by_code(code: str) -> dict | None:
    for track in TRACKS:
        if track["code"] == code:
            return track
    return None


def all_job_keywords() -> list[str]:
    """所有赛道的岗位词去重（用于检索）。"""
    words: list[str] = []
    for track in TRACKS:
        words.extend(track["jobs"])
    return list(dict.fromkeys(words))


def keyword_combos(track_code: str, limit: int = 24) -> list[str]:
    """为某个赛道生成"产品词 + 岗位词"的组合检索词。"""
    track = track_by_code(track_code)
    if not track:
        return []
    combos: list[str] = []
    for product in track["products"][:4]:
        for job in track["jobs"][:4]:
            combos.append(f"{product} {job}")
    for job in track["jobs"][:3]:
        combos.append(job)
    return list(dict.fromkeys(combos))[:limit]
